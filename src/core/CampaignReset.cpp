#include "CampaignReset.h"

namespace oem {
namespace {

bool hasPrefix(const std::string& value, const char* prefix) {
    const std::string p(prefix);
    return value.size() >= p.size() && value.compare(0, p.size(), p) == 0;
}

bool hasSuffix(const std::string& value, const char* suffix) {
    const std::string s(suffix);
    return value.size() >= s.size() &&
        value.compare(value.size() - s.size(), s.size(), s) == 0;
}

} // namespace

bool CampaignResetPolicy::isCampaignOwnedFileName(const std::string& name) {
    if (name == "economy.journal" || name == "events.journal")
        return true;

    // Per-location opening stocks are generated by OEM and are campaign data.
    if (hasPrefix(name, "cargo_stock_") && hasSuffix(name, ".cfg") &&
        name.size() > std::string("cargo_stock_").size() + std::string(".cfg").size())
        return true;

    // Reserved, versioned names for the contract/mission and manifest
    // persistence layers. Keeping the policy here makes future additions
    // explicit and testable before the native reset command can remove them.
    if (hasPrefix(name, "cargo_manifest_") &&
        (hasSuffix(name, ".journal") || hasSuffix(name, ".cfg")) &&
        name.size() > std::string("cargo_manifest_").size() + 7)
        return true;
    if (hasPrefix(name, "cargo_exchange_") && hasSuffix(name, ".journal") &&
        name.size() > std::string("cargo_exchange_").size() + std::string(".journal").size())
        return true;
    if (hasPrefix(name, "contract_") &&
        (hasSuffix(name, ".journal") || hasSuffix(name, ".cfg")) &&
        name.size() > std::string("contract_").size() + 7)
        return true;
    if (hasPrefix(name, "missions_") && hasSuffix(name, ".journal") &&
        name.size() > std::string("missions_").size() + std::string(".journal").size())
        return true;

    return false;
}

} // namespace oem
